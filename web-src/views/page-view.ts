// ヘッダメニューから開く 1 枚ものの画面が守る契約。
//
// app.ts が知るのはこの 4 つだけで、画面ごとの中身には触らない。ルート遷移で
// enter / suspend、言語切替で localize、サーバからの変更通知で handleSse を
// 呼ぶ。画面が増えるたびに app.ts 側の呼び出しの形が変わらないように、契約は
// ここ 1 箇所に置く。

export type PageView = {
  /**
   * その画面へ入る。最新を映している状態で同じ引数で呼び直したら何もしない
   * (server.md「ビュー切替 / enter 関数は冪等にする」)。
   */
  enter(): Promise<void>;
  /** その画面から出る。進行中の読み込みの結果は捨てる。 */
  suspend(): void;
  /** サーバからの変更通知。映していないなら何もしない。 */
  handleSse(): void;
  /** 表示言語が変わった。映していないなら何もしない。 */
  localize(): void;
};
